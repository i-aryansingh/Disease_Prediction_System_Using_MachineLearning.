"""Generate a SYNTHETIC demonstration dataset (not real patient data).

Each disease has a hand-written list of typical symptoms; rows are randomly
sampled from those lists with noise. It exists only so the app runs when the
project's original dataset is not available. Replace it with the real CSV.
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
PROFILES = {
    "Malaria": "high_fever chills sweating headache nausea vomiting body_ache fatigue",
    "Dengue": "high_fever headache pain_behind_eyes joint_pain muscle_pain skin_rash nausea fatigue",
    "Typhoid": "high_fever abdominal_pain headache loss_of_appetite constipation weakness diarrhoea",
    "Tuberculosis": "productive_cough blood_in_sputum weight_loss night_sweats mild_fever fatigue chest_pain loss_of_appetite",
    "Influenza": "mild_fever cough sore_throat runny_nose body_ache headache fatigue chills",
    "Pneumonia": "high_fever productive_cough shortness_of_breath chest_pain chills fatigue",
    "Chickenpox": "mild_fever skin_rash blisters itching fatigue headache loss_of_appetite",
    "Jaundice": "yellowing_of_skin yellowing_of_eyes dark_urine nausea abdominal_pain fatigue loss_of_appetite",
    "Gastroenteritis": "diarrhoea vomiting nausea abdominal_pain dehydration mild_fever weakness",
    "Migraine": "headache nausea vomiting light_sensitivity dizziness blurred_vision",
    "Asthma": "wheezing shortness_of_breath cough chest_pain",
    "Type 2 Diabetes": "excessive_thirst frequent_urination blurred_vision fatigue weight_loss itching",
    "Hypertension": "headache dizziness palpitations blurred_vision nosebleed chest_pain",
    "Anaemia": "pale_skin fatigue weakness dizziness palpitations shortness_of_breath",
    "Allergic Rhinitis": "sneezing runny_nose itchy_eyes cough sore_throat",
}


def main(seed=42):
    rng = np.random.default_rng(seed)
    profiles = {d: s.split() for d, s in PROFILES.items()}
    symptoms = sorted({s for v in profiles.values() for s in v})
    rows = []
    for disease, core in profiles.items():
        for _ in range(int(rng.integers(60, 161))):  # deliberately imbalanced classes
            while True:
                row = {s: int(rng.random() < (0.8 if s in core else 0.04)) for s in symptoms}
                if sum(row.values()) >= 2:
                    break
            row["prognosis"] = disease
            rows.append(row)
    df = pd.DataFrame(rows).sample(frac=1, random_state=seed).reset_index(drop=True)
    out = ROOT / "dataset"
    out.mkdir(exist_ok=True)
    df.to_csv(out / "disease_symptoms.csv", index=False)
    (out / "dataset_info.json").write_text(json.dumps({
        "is_demo": True,
        "description": "Synthetic demonstration data generated by backend/generate_demo_dataset.py. "
                       "Not real patient data and not medically validated.",
    }, indent=2), encoding="utf-8")
    print(f"Wrote {len(df)} synthetic rows, {len(symptoms)} symptoms, {len(profiles)} diseases.")


if __name__ == "__main__":
    main()
